USE NEPSorteosDB;
GO
IF OBJECT_ID('dbo.PrizeChats','U') IS NULL
CREATE TABLE dbo.PrizeChats(
 Id INT IDENTITY PRIMARY KEY,
 RaffleId INT NOT NULL UNIQUE REFERENCES dbo.Raffles(Id),
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
IF OBJECT_ID('dbo.PrizeMessages','U') IS NULL
CREATE TABLE dbo.PrizeMessages(
 Id INT IDENTITY PRIMARY KEY,
 ChatId INT NOT NULL REFERENCES dbo.PrizeChats(Id),
 SenderId INT NOT NULL REFERENCES dbo.Users(Id),
 Body NVARCHAR(2000) NOT NULL,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
IF OBJECT_ID('dbo.Testimonials','U') IS NULL
CREATE TABLE dbo.Testimonials(
 Id INT IDENTITY PRIMARY KEY,
 UserId INT NOT NULL UNIQUE REFERENCES dbo.Users(Id),
 Body NVARCHAR(1000) NOT NULL,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
IF OBJECT_ID('dbo.SupportRequests','U') IS NULL
CREATE TABLE dbo.SupportRequests(
 Id INT IDENTITY PRIMARY KEY,
 UserId INT NOT NULL REFERENCES dbo.Users(Id),
 Subject NVARCHAR(150) NOT NULL,
 Body NVARCHAR(2000) NOT NULL,
 Status VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
